import type { TimeOfDay } from './ai.js';
export type { TimeOfDay };

/** Suggested activity returned by the daily coach */
export interface CoachSuggestion {
  title: string;
  activityType: 'quantity' | 'duration' | 'completion';
  value: number;
  unit: string;
  /** Goal id the suggestion is linked to — may be null */
  goalId: string | null;
}

/** The full daily-coach AI response */
export interface DailyCoachResponse {
  /** 1-2 sentence motivational message personalised to recent work */
  message: string;
  /** Suggested activity for today */
  suggestion: CoachSuggestion | null;
  /** Short streak status line */
  streakMessage: string;
  /** Whether this was generated by AI or fell back to a quote */
  source: 'ai' | 'fallback';
}
