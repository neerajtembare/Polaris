/** Time-of-day bucket for personalised greeting/tone */
export type TimeOfDay = 'morning' | 'afternoon' | 'evening' | 'night';

/**
 * Shared context object assembled once per AI call.
 * Capped at 10 goals and 20 recent activities to avoid context-window bloat.
 */
export interface PolarisContext {
  activeGoals: Array<{
    id: string;
    title: string;
    /** 0–100 */
    progress: number;
    timeframe: string;
  }>;
  /** Last 7 days of activities — title + date string + type */
  recentActivities: Array<{
    title: string;
    date: string;
    type: string;
  }>;
  currentStreak: number;
  longestStreak: number;
  timeOfDay: TimeOfDay;
  dayOfWeek: string;
}

/** Suggested activity returned by the daily coach */
export interface CoachSuggestion {
  title: string;
  activityType: 'quantity' | 'duration' | 'completion';
  value: number;
  unit: string;
  /** Goal id the suggestion is linked to — may be null */
  goalId: string | null;
}

/** The full daily-coach AI response */
export interface DailyCoachResponse {
  /** 1-2 sentence motivational message personalised to recent work */
  message: string;
  /** Suggested activity for today */
  suggestion: CoachSuggestion | null;
  /** Short streak status line */
  streakMessage: string;
  /** Whether this was generated by AI or fell back to a quote */
  source: 'ai' | 'fallback';
}
